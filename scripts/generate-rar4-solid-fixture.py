#!/usr/bin/env python3
"""Optional developer-only fixture generation; never downloaded or run by clients.

Requires a separately installed/licensed RAR 6.24 CLI (RAR 7 cannot create RAR4).
Only original XLib fixture artwork is compressed. The resulting archive, not
the commercial development tool, is redistributed. Normal builds need no CLI.
"""
import argparse
import binascii
import json
import os
from pathlib import Path
import struct
import subprocess
import tempfile
import zipfile
from hashlib import sha256

ROOT = Path(__file__).resolve().parents[1]
FIXTURES = ROOT / "contracts/fixtures/documents"


def canonical_names(data):
    """Use the fixture profile's literal '/' paths, without changing solid data.

    RAR CLI writes backslashes even on macOS. XLib deliberately rejects raw
    backslashes. Rewrite only ASCII filename fields + header CRCs; compressed
    bodies, per-file CRCs and solid dictionary dependencies stay untouched.
    """
    data = bytearray(data)
    assert data[:7] == b"Rar!\x1a\x07\x00"
    offset = 7
    solid_members = 0
    while offset < len(data):
        crc, kind, flags, size = struct.unpack_from("<HBHH", data, offset)
        assert size >= 7 and offset + size <= len(data)
        assert crc == binascii.crc32(data[offset + 2:offset + size]) & 65535
        packed = struct.unpack_from("<I", data, offset + 7)[0] if flags & 0x8000 else 0
        if kind == 0x74:
            assert not flags & (0x100 | 0x200 | 0x7), "unexpected large/unicode/split/encrypted fixture header"
            length = struct.unpack_from("<H", data, offset + 26)[0]
            begin = offset + 32
            assert begin + length <= offset + size
            name = bytes(data[begin:begin + length]).decode("ascii")
            data[begin:begin + length] = name.replace("\\", "/").encode("ascii")
            struct.pack_into("<H", data, offset, binascii.crc32(data[offset + 2:offset + size]) & 65535)
            if flags & 0x10:
                solid_members += 1
        offset += size + packed
    assert offset == len(data) and solid_members >= 23
    return bytes(data)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--rar-tool", type=Path, required=True)
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix="xlib-solid-fixture-") as temporary:
        folder = Path(temporary)
        with zipfile.ZipFile(FIXTURES / "comic-basic.cbz") as archive:
            # This is a checked-in original fixture, not user-supplied content.
            archive.extractall(folder)
        # extractall doesn't restore ZIP timestamps. Fix DOS time, permissions
        # and timezone too; -ts- only suppresses extended timestamp fields.
        for item in folder.rglob("*"):
            item.chmod(0o755 if item.is_dir() else 0o644)
            os.utime(item, (1767225600, 1767225600))
        output = folder / "result.cbr"
        subprocess.run([str(args.rar_tool.resolve()), "a", "-cfg-", "-ma4", "-s", "-m5", "-mt1", "-ts-",
                        "-r", "-idq", str(output), "pages", "README.txt"], cwd=folder,
                       env={**os.environ, "TZ": "UTC"}, check=True)
        result = canonical_names(output.read_bytes())
    filename = "comic-basic-rar4-solid.cbr"
    (FIXTURES / filename).write_bytes(result)
    metadata = {
        "fixtureVersion": 1, "file": filename, "format": "cbr", "profile": "comic-order-v1",
        "generator": "scripts/generate-rar4-solid-fixture.py", "encoder": "RAR 6.24 -ma4 -s -m5 -mt1 -ts-",
        "license": "Original XLib fixture assets; same redistribution permission as comic-basic.cbz README.txt",
        "bookHash": sha256(result).hexdigest(), "fileSize": len(result), "pageCount": 24,
        "expectedPages": "comic-basic.json", "manifestHash": "1391ef2631b1495836a06541c65e8433eff9caae29643ebb2eb5f22c26af0e15",
        "notes": "RAR4 genuine compressed solid stream; ASCII path separators/header CRCs canonicalized, compressed bodies unchanged. Not generated by the normal dependency-free fixture check."
    }
    (FIXTURES / "comic-basic-rar4-solid.json").write_text(json.dumps(metadata, ensure_ascii=False, indent=2) + "\n")
    print(json.dumps({"file": filename, "bytes": len(result), "sha256": metadata["bookHash"]}))


if __name__ == "__main__":
    main()
