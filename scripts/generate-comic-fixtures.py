#!/usr/bin/env python3
"""Generate/check original synthetic comic fixtures, without image/font tools.

The PNGs use indexed colors and a tiny fixed-Huffman/run-length DEFLATE writer.
ZIP and minimal RAR4/RAR5 entries are stored with fixed metadata. No platform fonts, random seeds,
wall clock, zlib compressor versions, network resources or external artwork
affect the output. zlib is used only for specified CRC32/Adler32 and validation.
These generated images contain only original geometric marks and digit glyphs.
"""

