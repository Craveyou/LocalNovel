import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import vm from 'node:vm';
import { publications } from '../packages/kindle-core/test/fixtures.mjs';
const root = new URL('../', import.meta.url);
for (const file of ['entities.js', 'vendor/mobi.decoder.js', 'core.js']) vm.runInThisContext(readFileSync(new URL('packages/kindle-core/' + file, root), 'utf8'));
for (const [name, bytes] of Object.entries(publications())) {
    const parsed = XLibKindle.parse({size:bytes.length,read:(start,count)=>new Uint8Array(bytes.subarray(start,start+count))});
    const base = new URL('contracts/fixtures/documents/' + name, root);
    writeFileSync(base, bytes);
    writeFileSync(new URL(name + '.json', new URL('contracts/fixtures/documents/', root)), JSON.stringify({
        license:'CC0-1.0', source:'Original XLib test publication generated by scripts/generate-kindle-fixtures.mjs',
        sha256:createHash('sha256').update(bytes).digest('hex'), fileSize:bytes.length, mode:parsed.mode,
        profile:parsed.profile, canonicalText:parsed.canonicalText, coverResource:parsed.coverResource,
        textHash:createHash('sha256').update(parsed.canonicalText).digest('hex'),
        chapters:parsed.chapters.map(c=>({resource:c.resource,textStart:c.textStart,text:c.text,anchors:c.anchors,maps:c.maps})), toc:parsed.toc,
    }, null, 2) + '\n');
}
